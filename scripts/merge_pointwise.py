"""Append pointwise_montesinos.py results (JSON) for a knot to data/homfly/<knot>.txt,
with the transposed representations derived by H_{R^T}(A, q) = H_R(A, -1/q):

    python scripts/merge_pointwise.py 4_1 /path/4_1_*.json

Existing sections are kept; the header records the representations added.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from homfly.algebra.laurent import parse_laurent  # noqa: E402
from homfly.checks.structural import specialise_q1  # noqa: E402
from homfly.conventions import transpose_rep  # noqa: E402
from homfly.io.export import from_json  # noqa: E402
from homfly.reps.partitions import conjugate, partitions  # noqa: E402


def rep_str(R):
    return "[" + ",".join(map(str, R)) + "]"


def main():
    knot, files = sys.argv[1], sys.argv[2:]
    path = os.path.join(os.path.dirname(__file__), "..", "data", "homfly", knot + ".txt")
    text = open(path).read()
    have = set(re.findall(r"^R = (\[[0-9,]+\])$", text, re.M))
    H1 = parse_laurent(re.search(r"^R = \[1\]\n#.*\nH = (.*)$", text, re.M).group(1))
    q1 = specialise_q1(H1)
    new = {}
    for f in files:
        d = json.load(open(f))
        if not (d.get("verified") and d.get("q1_check")) or d.get("transposition_check") is False:
            raise SystemExit("unverified result %s" % f)
        R = tuple(d["R"])
        H = from_json(d["poly"])
        meta = "method=%s primes=%d verified=True q1_check=%%s transposition_check=%s" % (
            d["method"].replace(" ", "_"), d["primes"],
            "pointwise(%s)" % d.get("transposition_check") if "transposition_check" in d else "None")
        new[R] = (H, meta)
        RT = conjugate(R)
        if RT != R and RT not in new:
            new[RT] = (transpose_rep(H), meta.replace("method=", "method=transposed:") .replace(
                "transposition_check=pointwise(True)", "transposition_check=derived"))
    add = []
    sizes = sorted({sum(R) for R in new})
    for n in sizes:
        for R in partitions(n):
            R = tuple(R)
            if R not in new or rep_str(R) in have:
                continue
            H, meta = new[R]
            ok = specialise_q1(H) == q1 ** n
            if not ok:
                raise SystemExit("q=1 check failed for %s" % rep_str(R))
            add.append("R = %s\n# %s terms=%d\nH = %s\n" % (rep_str(R), meta % ok, len(H.terms),
                                                         H.to_string(mul="*", pow_="^")))
    if not add:
        print("nothing to add")
        return
    allR = set(re.findall(r"^R = (\[[0-9,]+\])$", text + "".join(add), re.M))
    full = [n for n in sizes if all(rep_str(tuple(R)) in allR for R in partitions(n))]
    part = [n for n in sizes if n not in full]
    note = ("# Added by scripts/merge_pointwise.py (pointwise mixed Racah engine, arborescent tangle "
            "calculus, 2 primes, fresh-point and q=1 checks, transposition checked at independent points): "
            "|R| = %s complete%s.\n" % (",".join(map(str, full)) or "-",
                                        "; |R| = %s partial" % ",".join(map(str, part)) if part else ""))
    lines = [L for L in text.split("\n") if not L.startswith("# Added by scripts/merge_pointwise.py")]
    i = next(k for k, L in enumerate(lines) if L.startswith("# Generated by"))
    lines.insert(i, note.rstrip("\n"))
    out = "\n".join(lines).rstrip("\n") + "\n\n" + "\n".join(add)
    open(path, "w").write(out)
    print("added %d sections to %s; complete sizes %s, partial %s" % (len(add), path, full, part))


if __name__ == "__main__":
    main()
