"""Symmetric [r] colored HOMFLY for r beyond the stored |R| (antisymmetric [1^r] by
transposition), written to data/homfly_symmetric/<knot>.txt.gz:

    python scripts/add_symmetric.py --rmin 7 --rmax 10 --jobs 3 [--knots 4_1 6_2 ...]

Only the fast exact methods are used (two-bridge, Montesinos, algebraic = arborescent
tangle calculus, torus); their Racah data for [r] are the root-free q-6j matrices of
racah_homfly (data/racah/montesinos/P_<r>.json.gz, see scripts/make_symmetric_racah.py).
Knots without such a presentation are skipped.  Each (knot, r) is cached in
<out>/.cache so that runs resume.  Check written per R: q = 1 -> H_[1]^r.
"""
import argparse
import json
import os
import re
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from homfly.compute import homfly  # noqa: E402
from homfly.conventions import transpose_rep  # noqa: E402
from homfly.io.export import from_json, to_json  # noqa: E402
from homfly.algebra.laurent import parse_laurent  # noqa: E402
from homfly.reconstruction.pipeline import ReconstructionReport  # noqa: E402

FAST = ("two-bridge", "montesinos", "algebraic", "rosso-jones", "double-braid-interpolation")


def rep_str(R):
    return "[" + ",".join(map(str, R)) + "]"


def task(name, r, cache):
    path = os.path.join(cache, "%s_%d.json" % (name, r))
    if os.path.exists(path):
        return json.load(open(path))
    from homfly.compute import default_methods, presentations, choose_method
    methods = [m for m in default_methods(None) if m.name in FAST]
    t = time.time()
    rep = ReconstructionReport()
    H = None
    for m in methods:
        try:
            choose_method(name, (r,), [m])
        except Exception:
            continue
        H = homfly(name, R=(r,), report=rep, method=m.name)
        break
    if H is None:
        res = {"knot": name, "R": [r], "skipped": True}
    else:
        res = {"knot": name, "R": [r], "method": rep.method, "seconds": round(time.time() - t, 1),
               "primes": len(rep.primes), "evaluations": rep.evaluations, "verified": rep.verified,
               "poly": to_json(H)}
    json.dump(res, open(path, "w"))
    return res


def append(name, out, new, data):
    """write the symmetric [r] of ``new`` ({r: result}) into <out>/<name>.txt.gz,
    keeping the sections already there"""
    import gzip
    path = os.path.join(out, name + ".txt.gz")
    secs = {}
    if os.path.exists(path):
        text = gzip.open(path, "rt").read()
        for blk in text.split("\n\n"):
            m = re.match(r"R = \[(\d+)\]\n", blk)
            if m:
                secs[int(m.group(1))] = blk.strip("\n")
    m = re.search(r"^R = \[1\]\n#.*\nH = (.*)$", open(os.path.join(data, name + ".txt")).read(), re.M)
    from homfly.checks.structural import specialise_q1
    q1ref = specialise_q1(parse_laurent(m.group(1)))
    added = 0
    for r in sorted(new):
        v = new[r]
        if r in secs or v.get("skipped") or "poly" not in v:
            continue
        H = from_json(v["poly"])
        ok = specialise_q1(H) == q1ref ** r
        if not ok:
            print("q=1 CHECK FAILED %s [%d]" % (name, r), flush=True)
        secs[r] = ("R = [%d]\n# method=%s primes=%d evaluations=%d verified=%s q1_check=%s terms=%d\nH = %s"
                   % (r, v["method"], v["primes"], v["evaluations"], v["verified"], ok, len(H.terms),
                      H.to_string(mul="*", pow_="^")))
        added += 1
    if not added:
        return 0
    head = ("# Reduced colored HOMFLY H_[r](A, q) of knot %s for symmetric [r], r = %s\n"
            "# (complements data/homfly/%s.txt; same conventions).  Antisymmetric: H_[1^r](A, q) = H_[r](A, -1/q).\n"
            "# Racah data: root-free q-6j matrices (data/racah/montesinos/P_<r>.json.gz).\n"
            "# Check per R: q=1 -> H_[1]^r.  Generated by scripts/add_symmetric.py\n"
            % (name, ",".join(map(str, sorted(secs))), name))
    with gzip.open(path, "wt") as f:
        f.write(head + "\n" + "\n\n".join(secs[r] for r in sorted(secs)) + "\n")
    return added


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rmin", type=int, default=7)
    ap.add_argument("--rmax", type=int, default=10)
    ap.add_argument("--knots", nargs="*")
    ap.add_argument("--data", default=os.path.join(os.path.dirname(__file__), "..", "data", "homfly"))
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "data", "homfly_symmetric"))
    ap.add_argument("--jobs", type=int, default=3)
    a = ap.parse_args()
    cache = os.path.join(a.out, ".cache")
    os.makedirs(cache, exist_ok=True)
    names = a.knots or sorted(f[:-4] for f in os.listdir(a.data) if f.endswith(".txt") and not f.startswith("L"))
    rs = list(range(a.rmin, a.rmax + 1))
    done = {n: {} for n in names}
    pending = {n: len(rs) for n in names}
    with ProcessPoolExecutor(a.jobs) as ex:
        futs = {ex.submit(task, n, r, cache): (n, r) for r in rs for n in names}
        for f in as_completed(futs):
            n, r = futs[f]
            try:
                res = f.result()
            except Exception as e:
                print("FAILED %s [%d]: %r" % (n, r, e), flush=True)
                res = {"skipped": True}
            done[n][r] = res
            if not res.get("skipped"):
                print("%-8s [%d] %-12s %7.1fs" % (n, r, res["method"], res["seconds"]), flush=True)
            pending[n] -= 1
            if pending[n] == 0:
                k = append(n, a.out, done[n], a.data)
                if k:
                    print("updated %s.txt.gz (+%d)" % (n, k), flush=True)


if __name__ == "__main__":
    main()
