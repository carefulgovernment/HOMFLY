def _mv(M, v, F):
    return [sum((M[i][j] * v[j] for j in range(len(v))), F.zero) for i in range(len(M))]


def _inv(M, F):
    from ..algebra.linalg import inverse
    return inverse(M, F.one)


def _mm(X, Y, F):
    return [[sum((X[i][k] * Y[k][j] for k in range(len(Y))), F.zero) for j in range(len(Y[0]))]
            for i in range(len(X))]


NP_BOUND = 2 ** 21       # float64 BLAS products are exact for p < 2^21, n < 2048


def _mm_np(X, Y, p):
    import numpy as np
    return np.fmod(X.astype(np.float64) @ Y.astype(np.float64), p).astype(np.int64)


def _inv_np(M, p):
    from .two_bridge import _inv_mod_np
    try:
        if M.shape[0] > 48:
            # M^-1 = G (M G)^-1 with a random G: M G has nonsingular leading
            # blocks with high probability even when M is sparse/structured
            import numpy as np
            G = np.random.default_rng(M.shape[0]).integers(0, p, M.shape)
            try:
                return _mm_np(G, _inv_blocked(_mm_np(M, G, p), p), p)
            except BadPoint:          # unlucky: pivoted elimination
                pass
        return _inv_mod_np(M, p)
    except BadPoint:
        raise BadPoint("singular Racah block")


def _inv_blocked(M, p):
    """Inverse by 2x2 Schur complements, products via exact float64 BLAS."""
    from .two_bridge import _inv_mod_np
    import numpy as np
    n = M.shape[0]
    if n <= 48:
        return _inv_mod_np(M, p)
    k = n // 2
    A, B, C, D = M[:k, :k], M[:k, k:], M[k:, :k], M[k:, k:]
    Ai = _inv_blocked(A, p)
    AiB, CAi = _mm_np(Ai, B, p), _mm_np(C, Ai, p)
    Si = _inv_blocked((D - _mm_np(C, AiB, p)) % p, p)
    X = _mm_np(AiB, Si, p)
    Y = _mm_np(Si, CAi, p)
    return np.block([[(Ai + _mm_np(X, CAi, p)) % p, (-X) % p], [(-Y) % p, Si]])


def natural_value_np(fracs, D, p):
    """``natural_value`` with numpy arrays mod p < NP_BOUND."""
    import numpy as np
    comps, tl = _orientations(tuple(Fraction(x) for x in fracs))
    if comps != 1:
        raise ValueError("Montesinos sum is not a knot")
    M = {("anti", "anti"): D["Sbar"], ("par", "anti"): D["V"], ("anti", "par"): D["S"]}
    Minv = {("par", "anti"): D["S"], ("anti", "par"): D["V"]}
    n = D["Sbar"].shape[0]
    tb, tp = D["Tbar"], D["T"]
    tbi = np.array([pow(int(x), -1, p) for x in tb], dtype=np.int64)
    tpi = np.array([pow(int(x), -1, p) for x in tp], dtype=np.int64)

    def pw(ev, evi, e):
        base = ev if e > 0 else evi
        out = np.ones(n, dtype=np.int64)
        for _ in range(abs(e)):
            out = out * base % p
        return out
    vecs, verts = [], []
    for base, ops, steps in tl:
        basis = "V" if base == "0" else "H"
        v = np.zeros(n, dtype=np.int64)
        v[D["vac"]] = 1
        for (kind, s), o in zip(ops, steps[:-1]):
            h, vv = _types(o)
            if kind == "H":
                if basis == "V":
                    v, basis = _mm_np(M[(h, vv)], v[:, None], p)[:, 0], "H"
                ev, evi, e = (tb, tbi, s * GROUP) if h == "anti" else (tp, tpi, -s)
            else:
                if basis == "H":
                    key = (h, vv)
                    if key not in Minv:
                        Minv[key] = _inv_np(M[key], p)
                    v, basis = _mm_np(Minv[key], v[:, None], p)[:, 0], "V"
                ev, evi, e = (tb, tbi, s) if vv == "anti" else (tp, tpi, -s * GROUP)
            v = v * pw(ev, evi, e) % p
        if basis == "V":
            v = _mm_np(M[_types(steps[-1])], v[:, None], p)[:, 0]
        vecs.append(v)
        verts.append(_types(steps[-1])[0])
    vert = verts[0]
    E = (D["Sbar"] if vert == "anti" else D["V"])[:, D["vac"]]
    dims = D["d_anti"] if vert == "anti" else D["d_par"]
    blocks = D["blocks_anti"] if vert == "anti" else D["blocks_par"]
    tot = 0
    by_shape = {}
    for idx in blocks:
        by_shape.setdefault((len(idx), len(idx[0])), []).append(idx)
    for idxs in by_shape.values():         # all blocks of one shape at once
        ix = np.array(idxs)
        Ei = _inv_stack(E[ix], p)
        prod = None
        for v in vecs:
            X = _mm_np(v[ix], Ei, p)
            prod = X if prod is None else _mm_np(prod, X, p)
        tr = np.trace(prod, axis1=1, axis2=2) % p
        tot = (tot + int((dims[ix[:, 0, 0]] * tr % p).sum() % p)) % p
    return tot * pow(int(D["dR"]), -1, p) % p


def _inv_stack(M, p):
    """Inverses of a stack of small matrices (Gauss--Jordan, vectorised over
    the stack; a zero pivot falls back to pivoted elimination per matrix)."""
    import numpy as np
    m, n, _ = M.shape
    X = np.concatenate([M % p, np.broadcast_to(np.eye(n, dtype=np.int64), (m, n, n))], axis=2)
    for c in range(n):
        piv = X[:, c, c]
        if not piv.all():
            return np.array([_inv_np(B, p) for B in M])
        X[:, c] = X[:, c] * _inv_vec(piv, p)[:, None] % p
        f = X[:, :, c].copy()
        f[:, c] = 0
        X = (X - f[:, :, None] * X[:, c][:, None, :]) % p
    return X[:, :, n:]


