class _Poly:
    __slots__ = ("terms",)

    def __init__(self, terms):
        self.terms = [tuple(t) for t in terms]

    def ev(self, F, A, q, cache):
        s = F.zero
        for i, j, c in self.terms:
            k = (i, j)
            if k not in cache:
                cache[k] = A ** i * q ** j
            s = s + cache[k] * c
        return s


class _Flat:
    """Matrix of rational entries num/den for vectorised evaluation mod p."""

    def __init__(self, mat):
        self.shape = (len(mat), len(mat[0]))
        self.parts = []
        for which in (0, 1):
            coef, ai, qj, ptr = [], [], [], []
            for row in mat:
                for e in row:
                    ptr.append(len(coef))
                    terms = e[which].terms or [(0, 0, 0)]
                    for i, j, c in terms:
                        ai.append(i)
                        qj.append(j)
                        coef.append(c)
            self.parts.append((coef, ai, qj, ptr))
        self._np = None
        self._coef = {}
        self._row = {}

    def _prepare(self):
        """Static grouping of the terms by (entry, A-exponent), so that for a
        fixed q (interpolation evaluates whole rows of A-points at one q) every
        entry collapses to a short polynomial in A."""
        import numpy as np
        self._np = []
        for coef, ai, qj, ptr in self.parts:
            ai, qj, ptr = np.array(ai), np.array(qj), np.array(ptr)
            entry = np.repeat(np.arange(len(ptr)), np.diff(np.append(ptr, len(ai))))
            key = entry * (int(ai.max()) - int(ai.min()) + 1) + (ai - ai.min())
            order = np.argsort(key, kind="stable")
            ks = key[order]
            starts = np.flatnonzero(np.r_[True, ks[1:] != ks[:-1]])
            g_entry, g_ai = entry[order][starts], ai[order][starts]
            g_ptr = np.flatnonzero(np.r_[True, g_entry[1:] != g_entry[:-1]])
            self._np.append((ai, qj, ptr, order, starts, g_ai, g_ptr))

    def evaluate(self, p, pw, q=None):
        import numpy as np
        if self._np is None:
            self._prepare()
        vals = []
        for which in (0, 1):
            key = (which, p)
            if key not in self._coef:
                self._coef[key] = np.array([int(c) % p for c in self.parts[which][0]], dtype=np.int64)
            ai, qj, ptr, order, starts, g_ai, g_ptr = self._np[which]
            if q is None:
                t = self._coef[key] * pw("A", ai) % p * pw("q", qj) % p
                vals.append(np.add.reduceat(t, ptr) % p)
                continue
            ck = (which, p, q)
            if self._row.get(which, (None,))[0] != ck:
                t = (self._coef[key] * pw("q", qj) % p)[order]
                self._row[which] = (ck, np.add.reduceat(t, starts) % p)
            t = self._row[which][1] * pw("A", g_ai) % p
            vals.append(np.add.reduceat(t, g_ptr) % p)
        num, den = vals
        if (den == 0).any():
            raise BadPoint("pole in Racah data")
        return (num * _inv_vec(den, p) % p).reshape(self.shape)


def _inv_vec(x, p):
    """Elementwise inverse mod p < 2^31 (Fermat, vectorised)."""
    import numpy as np
    out = np.ones_like(x)
    b, e = x % p, p - 2
    while e:
        if e & 1:
            out = out * b % p
        b = b * b % p
        e >>= 1
    return out


def _powers(p, A, q):
    """pw(var, exponents array) -> A^e or q^e mod p, from a cached table."""
    import numpy as np
    tabs = {}

    def pw(var, e):
        x = A if var == "A" else q
        lo, hi = int(e.min()), int(e.max())
        if var not in tabs or tabs[var][0] > lo or tabs[var][1] < hi:
            xi = pow(x, -1, p)
            tab = [pow(xi, -k, p) if k < 0 else pow(x, k, p) for k in range(lo, hi + 1)]
            tabs[var] = (lo, hi, np.array(tab, dtype=np.int64))
        lo0, _, tab = tabs[var]
        return tab[e - lo0]
    return pw


class PData:
    """Family P, multiplicity-free R: S̄, S, V, T, T̄."""

    def __init__(self, R, root=DATA_DIR):
        with gzip.open(os.path.join(root, "P_%s.json.gz" % "".join(map(str, R))), "rt") as f:
            d = json.load(f)
        self.R = tuple(R)
        self.vac = d["vacuum_index"]
        self.mats = {k: [[(_Poly(n), _Poly(dd)) for n, dd in row] for row in d[k]]
                     for k in ("Sbar", "S", "V")}
        self.diags = {k: [(_Poly(n), _Poly(dd)) for n, dd in d[k]] for k in ("T", "Tbar")}
        self.n = len(d["Sbar"])
        self.flat = {k: _Flat(M) for k, M in self.mats.items()}
        self.flat.update({k: _Flat([v]) for k, v in self.diags.items()})

    def evaluate_np(self, p, A, q):
        import numpy as np
        pw = _powers(p, A, q)
        out = {k: f.evaluate(p, pw, q) for k, f in self.flat.items()}
        out["T"], out["Tbar"] = out["T"][0], out["Tbar"][0]
        F = GF(p)
        dR = int(qdim(self.R, F(A), F(q)))
        Sb, S, V, z = out["Sbar"], out["S"], out["V"], self.vac
        out["d_anti"] = Sb[z, :] * Sb[:, z] % p * (dR * dR % p) % p
        out["d_par"] = S[z, :] * V[:, z] % p * (dR * dR % p) % p
        out["dR"] = dR
        out["blocks_anti"] = [[[X]] for X in range(self.n)]
        out["blocks_par"] = [[[Qi]] for Qi in range(self.n)]
        out["vac"] = z
        return {k: (np.asarray(v, dtype=np.int64) if k in ("d_anti", "d_par") else v)
                for k, v in out.items()}

    def evaluate(self, F, A, q):
        cache = {}

        def ev(e):
            den = e[1].ev(F, A, q, cache)
            if den == 0:
                raise BadPoint("pole in Racah data")
            return e[0].ev(F, A, q, cache) / den
        out = {k: [[ev(e) for e in row] for row in M] for k, M in self.mats.items()}
        out.update({k: [ev(e) for e in v] for k, v in self.diags.items()})
        dR = qdim(self.R, A, q)
        Sb, S, V = out["Sbar"], out["S"], out["V"]
        z = self.vac
        out["d_anti"] = [Sb[z][X] * Sb[X][z] * dR * dR for X in range(self.n)]
        out["d_par"] = [S[z][Qi] * V[Qi][z] * dR * dR for Qi in range(self.n)]
        out["dR"] = dR
        out["blocks_anti"] = [[[X]] for X in range(self.n)]     # 1x1 blocks
        out["blocks_par"] = [[[Qi]] for Qi in range(self.n)]
        return out


class HData:
    """Family H (Hecke Y-gauge): S̄, mixed S with explicit (X,a,b)/(Q,a,b)
    labels -> multiplicity blocks."""

    def __init__(self, R, root=DATA_DIR, family="H"):
        with gzip.open(os.path.join(root, "%s_%s.json.gz" % (family, "".join(map(str, R)))), "rt") as f:
            d = json.load(f)
        self.R = tuple(R)
        self.family = family
        self.anti, self.par = d["anti"], d["par"]
        self.mats = {k: [[(_Poly(n), _Poly(dd)) for n, dd in row] for row in d[k]]
                     for k in ("Sbar", "S") if k in d}
        self.Tpar = d["T"]
        self.n = len(self.anti)
        self.blocks_anti = self._blocks([((tuple(x["Z"]), tuple(x["Zp"])), x["a"], x["b"])
                                         for x in self.anti])
        self.blocks_par = self._blocks([(tuple(x["Q"]), x["a"], x["b"]) for x in self.par])
        self.vac = next(i for i, x in enumerate(self.anti) if not x["Z"] and not x["Zp"])
        self.flat = {k: _Flat(M) for k, M in self.mats.items()}

    def evaluate_np(self, p, A, q):
        import numpy as np
        from ..reps.partitions import kappa
        from .interpolation import Point
        F = GF(p)
        pw = _powers(p, A, q)
        S = self.flat["S"].evaluate(p, pw, q)
        Sinv = _inv_np(S, p)
        FA, Fq = F(A), F(q)
        theta = FA ** sum(self.R) * Fq ** (2 * kappa(self.R))
        T = np.array([int(sg * FA ** ea * Fq ** eq / theta) for sg, ea, eq in self.Tpar], dtype=np.int64)
        Tb = np.array([int(x["eps"] * FA ** sum(x["Z"]) * Fq ** (kappa(tuple(x["Z"])) + kappa(tuple(x["Zp"]))))
                       for x in self.anti], dtype=np.int64)
        if self.family == "G":
            K = _mm_np(Sinv, T[:, None] * S % p, p)
            Sb = Tb[:, None] * K % p * Tb[None, :] % p
        else:
            Sb = self.flat["Sbar"].evaluate(p, pw, q)
        pt = Point(F, FA, Fq)
        d_anti = np.zeros(self.n, dtype=np.int64)
        for (Z, Zp), idx in self.blocks_anti:
            d_anti[[i for row in idx for i in row]] = int(pt.chi((), Z, Zp))
        d_par = np.zeros(self.n, dtype=np.int64)
        for Q, idx in self.blocks_par:
            d_par[[i for row in idx for i in row]] = int(qdim(Q, FA, Fq))
        return {"Sbar": Sb, "V": S, "S": Sinv, "T": T, "Tbar": Tb, "dR": int(qdim(self.R, FA, Fq)),
                "d_anti": d_anti, "d_par": d_par,
                "blocks_anti": [idx for _, idx in self.blocks_anti],
                "blocks_par": [idx for _, idx in self.blocks_par], "vac": self.vac}

    @staticmethod
    def _blocks(labels):
        groups = {}
        for i, (key, a, b) in enumerate(labels):
            groups.setdefault(key, []).append((a, b, i))
        out = []
        for key, items in groups.items():
            As = sorted({a for a, _, _ in items})
            Bs = sorted({b for _, b, _ in items})
            pos = {(a, b): i for a, b, i in items}
            out.append((key, [[pos[(a, b)] for b in Bs] for a in As]))
        return out

    def evaluate(self, F, A, q):
        from ..reps.partitions import kappa
        from .interpolation import Point
        cache = {}

        def ev(e):
            den = e[1].ev(F, A, q, cache)
            if den == 0:
                raise BadPoint("pole in Racah data")
            return e[0].ev(F, A, q, cache) / den
        S = [[ev(e) for e in row] for row in self.mats["S"]]
        Sb = [[ev(e) for e in row] for row in self.mats["Sbar"]] if "Sbar" in self.mats else None
        Sinv = _inv(S, F)
        dR = qdim(self.R, A, q)
        theta = A ** sum(self.R) * q ** (2 * kappa(self.R))
        T = [sg * A ** ea * q ** eq / theta for sg, ea, eq in self.Tpar]
        Tb = [x["eps"] * A ** sum(x["Z"]) * q ** (kappa(tuple(x["Z"])) + kappa(tuple(x["Zp"])))
              for x in self.anti]
        if self.family == "G":
            # family H satisfies T̄^-1 S̄ T̄^-1 = S^-1 T S; family G publishes S̄
            # in a vacuum-dual gauge (rows and columns normalised differently),
            # so S̄ is rebuilt from this identity in the gauge of S's columns
            K = _mm(Sinv, [[T[i] * S[i][j] for j in range(len(S))] for i in range(len(S))], F)
            Sb = [[Tb[i] * K[i][j] * Tb[j] for j in range(len(S))] for i in range(len(S))]
        pt = Point(F, A, q)
        d_anti = [F.zero] * self.n
        for (Z, Zp), idx in self.blocks_anti:
            dX = pt.chi((), Z, Zp)
            for row in idx:
                for i in row:
                    d_anti[i] = dX
        d_par = [F.zero] * self.n
        for Q, idx in self.blocks_par:
            dQ = qdim(Q, A, q)
            for row in idx:
                for i in row:
                    d_par[i] = dQ
        # engine slots: V = (par,anti) transform c_Hpar = V v_Vanti ; S = (anti,par)
        return {"Sbar": Sb, "V": S, "S": Sinv, "T": T, "Tbar": Tb, "dR": dR,
                "d_anti": d_anti, "d_par": d_par,
                "blocks_anti": [idx for _, idx in self.blocks_anti],
                "blocks_par": [idx for _, idx in self.blocks_par], "vac": self.vac}


@lru_cache(maxsize=None)
def load(R, root=DATA_DIR):
    R = tuple(R)
    key = "".join(map(str, R))
    if os.path.exists(os.path.join(root, "P_%s.json.gz" % key)):
        return PData(R, root)
    if os.path.exists(os.path.join(root, "H_%s.json.gz" % key)):
        return HData(R, root, "H")
    return HData(R, root, "G")


@lru_cache(maxsize=None)
def available(root=DATA_DIR):
    if not os.path.isdir(root):
        return []
    return sorted({tuple(int(c) for c in f[2:-8]) for f in os.listdir(root)
                   if f[:2] in ("P_", "H_", "G_") and f.endswith(".json.gz")})


